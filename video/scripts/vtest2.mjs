import { chromium as pw } from 'playwright-core';
import sparticuz from '@sparticuz/chromium';
const exe = await sparticuz.executablePath();
const b = await pw.launch({ executablePath: exe, headless: true, args: [...sparticuz.args.filter((a) => !a.startsWith('--single-process')), '--font-render-hinting=none', '--disable-lcd-text'] });
const ctx = await b.newContext({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1, recordVideo: { dir: 'out/vid-t', size: { width: 1920, height: 1080 } } });
const p = await ctx.newPage();
await p.goto('http://localhost:5173/login', { waitUntil: 'networkidle' });
await p.getByRole('button', { name: /Acesso de demonstração/ }).click();
await p.waitForTimeout(300);
await p.getByRole('button', { name: /Helena/ }).first().click();
await p.waitForTimeout(1500);
await p.goto('http://localhost:5173/documentos', { waitUntil: 'networkidle' });
await p.waitForTimeout(1000);
const t0 = Date.now();
await p.evaluate(() => { const r = document.getElementById('root'); r.style.transition = 'transform 2500ms linear'; r.style.transformOrigin = '600px 300px'; r.style.transform = 'scale(1.6)'; });
await p.waitForTimeout(2600);
await p.evaluate(() => { const r = document.getElementById('root'); r.style.transform = 'scale(1)'; });
await p.waitForTimeout(2600);
console.log('elapsed', Date.now() - t0);
const v = p.video();
await ctx.close(); await b.close();
console.log('video', await v.path());
